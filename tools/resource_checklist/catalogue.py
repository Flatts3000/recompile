keep, dropped = {}, []
for item, paths in src.items():
    # Evidence tiers: natural generation is stronger evidence of "where this comes from"
    # than a mob that wanders, which is stronger than a block sitting in a structure.
    T = {1: set(), 2: set(), 3: set(), 4: set(), 5: set()}
    why = []
    for p in paths:
        if p.startswith("blocks/"):
            b = "minecraft:" + p.split("/", 1)[1]
            if b in WORLDGEN:
                tier = 1 if b in NATURAL else 3
                T[tier] |= blk_dom.get(b, {"Overworld (other)"})
                why.append("mine " + p.split("/", 1)[1])
        elif p.startswith("entities/"):
            nm = p.split("/", 1)[1]
            base = nm.split("/")[0]
            got = mob_dom.get("minecraft:" + base, set())
            if not got:
                fb = MOB_FALLBACK.get(base)
                if fb:
                    got = {fb}
            T[2] |= got
            why.append("kill " + base)
        elif p.startswith("chests/"):
            n = p.split("/", 1)[1]
            if any(k in n for k in ("nether", "bastion", "ruined_portal")):
                T[3].add("Nether")
            elif "end_city" in n:
                T[3].add("End")
            elif any(k in n for k in ("shipwreck", "buried_treasure", "underwater", "ocean_ruin")):
                T[3].add("Ocean")
            else:
                T[3].add("Structures & Chest Loot")
            why.append("chest " + n)
        elif p.startswith("trade/"):
            T[4].add("Trading")
            why.append("trade " + p.split("/", 1)[1].split("/")[0])
        elif p.startswith("archaeology/"):
            T[4].add("Archaeology")
            why.append("brush " + p.split("/", 1)[1])
        elif p.startswith("gameplay/fishing"):
            T[4].add("Fishing")
            why.append("fishing")
        elif p.startswith("gameplay/hero_of_the_village"):
            T[4].add("Trading")
            why.append("hero of the village gift")
        elif p.startswith("shearing/"):
            T[5].add("Overworld (other)")
            why.append("shear " + p.split("/", 1)[1].split("/")[0])
        elif p.startswith("harvest/"):
            T[5].add("Overworld (other)")
            why.append("harvest " + p.split("/", 1)[1])
        elif p.startswith("charged_creeper/"):
            T[5].add("Overworld (other)")
            why.append("charged creeper kills " + p.split("/", 1)[1])
        elif p.startswith(("pots/", "spawners/", "equipment/", "dispensers/")):
            T[3].add("Structures & Chest Loot")
            why.append(HOW.get(p, p.split("/")[0] + " (trial chambers)"))
        elif p in HOW:
            T[5].add("Overworld (other)")
            why.append(HOW[p])
        elif p.startswith("gameplay/"):
            T[5].add("Overworld (other)")
            why.append(p.split("/", 1)[1])
    D = T[1] | T[2] | T[3] | T[4] | T[5]
    best_tier = next((t for t in (1, 2, 3, 4, 5) if T[t]), None)
    best = T[best_tier] if best_tier else set()
    if not D:
        dropped.append(item)
        continue
    if item in PRIMARY_OVERRIDE:
        prim = PRIMARY_OVERRIDE[item]
    elif is_wood(item):
        prim = "Wood"
    elif item in UNDER:
        prim = "Cave & Underground"
    elif len(best & OW_BIOME) >= 3:
        # spans many overworld biomes -> generic, not biome-specific
        prim = "Overworld (other)"
    elif best_tier == 3 and len(best) >= 3:
        # turns up in several unrelated structures -> generic structure loot
        prim = "Structures & Chest Loot"
    elif "Overworld (other)" in best and item in SURFACE_ITEMS:
        # ordinary terrain that also happens to line a cave biome
        prim = "Overworld (other)"
    else:
        prim = next((d for d in DOMS if d in best), "Other")
    # A craftable block whose only appearance is inside a structure's palette is decoration,
    # not a resource: you can mine a fence out of a shipwreck, but that is not where fences
    # come from. Flag it so the checklist can demote it out of the main rows.
    mined = [w[5:] for w in why if w.startswith("mine ")]
    struct_only = (item in craft and len(mined) == len(why) and mined
                   and all("minecraft:" + b not in NATURAL for b in mined))
    keep[item] = {"primary": prim, "domains": sorted(D), "why": sorted(set(why)),
                  "craftable": item in craft, "struct_only": bool(struct_only)}

for item, extra in WHY_EXTRA.items():
    if item in keep and extra not in keep[item]["why"]:
        keep[item]["why"] = sorted(keep[item]["why"] + [extra])

for item, (dom, how) in MANUAL.items():
    if item in keep:
        continue
    keep[item] = {"primary": dom, "domains": [dom], "why": [how], "craftable": item in craft}
    if item in dropped:
        dropped.remove(item)

