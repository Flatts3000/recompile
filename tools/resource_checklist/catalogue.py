def walkn(o, acc):
    if isinstance(o, dict):
        n = o.get("Name")
        if isinstance(n, str):
            acc.add(n)
        for v in o.values():
            walkn(v, acc)
    elif isinstance(o, list):
        for v in o:
            walkn(v, acc)


