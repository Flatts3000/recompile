WOOD_SUFF = ("_log", "_wood", "_leaves", "_sapling", "_planks", "_stem", "_hyphae", "_propagule")


def is_wood(i):
    s = i.replace("minecraft:", "")
    if s.endswith("_stem") and s in ("melon_stem", "pumpkin_stem"):
        return False
    return s.endswith(WOOD_SUFF) or s in ("bamboo", "stripped_bamboo_block", "bamboo_block", "stick")


